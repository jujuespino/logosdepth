"""The whole Bible: browse any chapter and fetch any passage to memorize.

Data is generated by scripts/build_bible.py into data/bible/ (KJV for every verse, WEB where it lines up with
the KJV numbering). Everything here is read-only and public.
"""
import json
import re
from functools import lru_cache
from pathlib import Path

from flask import Blueprint, jsonify, request

bp = Blueprint("bible", __name__)
DATA = Path(__file__).resolve().parent / "data" / "bible"
MAX_VERSES = 12          # longest passage fetched in one go
MAX_WORDS = 160          # longest passage the learning steps are meant for
REF = re.compile(r"^(?P<book>[1-3]? ?[A-Za-z][A-Za-z' ]*?) (?P<ch>\d{1,3}):(?P<a>\d{1,3})(?:-(?P<b>\d{1,3}))?$")


@lru_cache(maxsize=1)
def _index() -> list[dict]:
    return json.loads((DATA / "index.json").read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def _by_ref_name() -> dict[str, dict]:
    out = {}
    for b in _index():
        out[b["ref_name"].lower()] = b
        out[b["name"].lower()] = b
    return out


@lru_cache(maxsize=8)
def _book(slug: str) -> dict:
    return json.loads((DATA / f"{slug}.json").read_text(encoding="utf-8"))


@bp.after_request
def _cache(resp):
    resp.headers["Cache-Control"] = "public, max-age=3600"
    return resp


@bp.route("/api/bible")
def books():
    return jsonify(_index())


@bp.route("/api/bible/<slug>/<int:chapter>")
def chapter(slug: str, chapter: int):
    meta = next((b for b in _index() if b["slug"] == slug), None)
    if not meta or not 1 <= chapter <= len(meta["chapters"]):
        return jsonify({"error": "No such chapter."}), 404
    verses = _book(slug)["chapters"][chapter - 1]
    return jsonify({
        "book": meta["name"], "ref_name": meta["ref_name"], "slug": slug, "chapter": chapter,
        "verses": [{"n": i + 1, "kjv": v[0], "web": v[1]} for i, v in enumerate(verses)],
    })


def passage_for(ref: str):
    """Return (payload, error)."""
    ref = ref.strip()
    m = REF.match(ref) if len(ref) <= 40 else None
    if not m:
        return None, "That does not look like a Bible reference, for example John 3:16 or Psalm 23:1-3."
    meta = _by_ref_name().get(m["book"].strip().lower())
    if not meta:
        return None, "Unknown book."
    ch, a = int(m["ch"]), int(m["a"])
    b = int(m["b"] or a)
    if not 1 <= ch <= len(meta["chapters"]) or not 1 <= a <= b <= meta["chapters"][ch - 1]:
        return None, "That chapter or verse does not exist."
    if b - a + 1 > MAX_VERSES:
        return None, f"Choose at most {MAX_VERSES} verses at a time."
    verses = _book(meta["slug"])["chapters"][ch - 1][a - 1:b]
    text = " ".join(v[0] for v in verses)
    if len(text.split()) > MAX_WORDS:
        return None, f"That passage is longer than {MAX_WORDS} words. Choose a shorter range."
    out = {"ref": f"{meta['ref_name']} {ch}:{a}" + (f"-{b}" if b != a else ""), "text": text, "packs": ["mine"]}
    if all(v[1] for v in verses):
        out["translations"] = {"web": " ".join(v[1] for v in verses)}
    return out, None


@bp.route("/api/passage")
def passage():
    data, err = passage_for(request.args.get("ref", ""))
    if err:
        return jsonify({"error": err}), 400
    return jsonify(data)
